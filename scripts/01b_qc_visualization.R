message_step <- function(x) {

  message(
    "\n========== ",
    x,
    " =========="
  )
}


check_file <- function(
  path,
  label = "file"
) {

  if (!file.exists(path)) {

    stop(
      "File does not exist - ",
      label,
      ": ",
      path
    )
  }
}


get_config_value <- function(
  config,
  path,
  default = NULL
) {

  parts <- strsplit(
    path,
    "\\."
  )[[1]]

  value <- config

  for (p in parts) {

    if (
      is.null(value) ||
      is.null(value[[p]])
    ) {
      return(default)
    }

    value <- value[[p]]
  }

  value
}


safe_save_plot <- function(
  plot,
  filename,
  width = 8,
  height = 5,
  dpi = 150
) {

  ggsave(
    filename = filename,
    plot = plot,
    width = width,
    height = height,
    dpi = dpi,
    limitsize = FALSE
  )

  message(
    "Plot saved: ",
    filename
  )
}


safe_median <- function(x) {

  x <- suppressWarnings(
    as.numeric(x)
  )

  x <- x[
    is.finite(x)
  ]

  if (length(x) == 0) {
    return(NA_real_)
  }

  median(x)
}


deterministic_downsample <- function(
  metadata,
  max_points
) {

  if (
    is.null(max_points) ||
    is.na(max_points) ||
    max_points <= 0 ||
    nrow(metadata) <= max_points
  ) {

    return(metadata)
  }

  index <- unique(
    round(
      seq(
        from = 1,
        to = nrow(metadata),
        length.out = max_points
      )
    )
  )

  metadata[
    index,
    ,
    drop = FALSE
  ]
}


summarise_by <- function(
  metadata,
  grouping_columns
) {

  grouping_columns <- grouping_columns[
    grouping_columns %in%
      colnames(metadata)
  ]

  if (length(grouping_columns) == 0) {
    return(NULL)
  }

  metadata %>%
    as_tibble() %>%
    group_by(
      across(
        all_of(grouping_columns)
      ),
      .drop = FALSE
    ) %>%
    summarise(
      cells = n(),
      median_nCount_RNA =
        safe_median(nCount_RNA),
      median_nFeature_RNA =
        safe_median(nFeature_RNA),
      median_percent_mito =
        safe_median(percent.mito),
      median_percent_ribo =
        safe_median(percent.ribo),
      median_percent_globin =
        safe_median(percent.globin),
      median_log10GenesPerUMI =
        safe_median(log10GenesPerUMI),
      median_nCount_ADT = if (
        "nCount_ADT" %in%
          colnames(metadata)
      ) {
        safe_median(nCount_ADT)
      } else {
        NA_real_
      },
      median_nFeature_ADT = if (
        "nFeature_ADT" %in%
          colnames(metadata)
      ) {
        safe_median(nFeature_ADT)
      } else {
        NA_real_
      },
      .groups = "drop"
    )
}


make_violin_plot <- function(
  metadata,
  x_column,
  y_column,
  title,
  x_label,
  y_label
) {

  ggplot(
    metadata,
    aes(
      x = .data[[x_column]],
      y = .data[[y_column]]
    )
  ) +
    geom_violin(
      scale = "width",
      trim = TRUE,
      na.rm = TRUE
    ) +
    geom_boxplot(
      width = 0.1,
      outlier.shape = NA,
      na.rm = TRUE
    ) +
    theme_bw() +
    theme(
      axis.text.x =
        element_text(
          angle = 45,
          hjust = 1
        )
    ) +
    labs(
      title = title,
      x = x_label,
      y = y_label
    )
}


write_optional_csv <- function(
  x,
  filename
) {

  if (is.null(x)) {
    return(invisible(NULL))
  }

  readr::write_csv(
    x,
    filename
  )

  message(
    "Summary saved: ",
    filename
  )

  invisible(NULL)
}


