# ==============================================================================
# 01b_qc_visualization.R
#
# Generic, non-destructive visualization of QC metrics produced by 01a.
#
# RESPONSIBILITIES
#   ✓ visualize QC metrics by sample
#   ✓ optionally visualize QC metrics by capture
#   ✓ optionally visualize QC metrics by group
#   ✓ preserve the input object untouched
#   ✓ use canonical qc_sample_id / qc_group from 01a
#   ✓ avoid re-exporting huge redundant cell-level metadata by default
#   ✓ downsample scatter plots deterministically for large datasets
#
# THIS SCRIPT MUST NOT
#   ✗ filter cells
#   ✗ change metadata
#   ✗ remove multiplets / undetermined / unmapped cells
#   ✗ normalize
#   ✗ run dimensional reduction
#   ✗ decide QC thresholds
#   ✗ decide doublet status
# ==============================================================================


# ==============================================================================
# CLI
# ==============================================================================

