#!/usr/bin/env Rscript

suppressPackageStartupMessages({
  library(optparse)
  library(yaml)
  library(Seurat)
  library(dplyr)
  library(readr)
  library(tibble)
})

# ============================================================
# Arguments
# ============================================================

option_list <- list(
  make_option(
    c("--input"),
    type = "character",
    default = NULL,
    help = "Input Seurat RDS object generated by LOAD_DATA"
  ),
  make_option(
    c("--config"),
    type = "character",
    default = NULL,
    help = "YAML configuration file"
  ),
  make_option(
    c("--output"),
    type = "character",
    default = "seu_qc_metrics.rds",
    help = "Output Seurat object with QC metrics"
  )
)

opt <- parse_args(
  OptionParser(option_list = option_list)
)

if (is.null(opt$input)) {
  stop("Missing required argument: --input")
}

if (is.null(opt$config)) {
  stop("Missing required argument: --config")
}

# ============================================================
# Helpers
# ============================================================

message_step <- function(message_text) {
  message(
    "\n========== ",
    message_text,
    " =========="
  )
}

check_file <- function(path, label = "file") {
  if (!file.exists(path)) {
    stop(
      paste0(
        "File does not exist - ",
        label,
        ": ",
        path
      )
    )
  }
}

get_config_value <- function(
  config,
  path,
  default = NULL
) {
  parts <- strsplit(path, "\\.")[[1]]
  value <- config

  for (part in parts) {
    if (
      is.null(value) ||
      is.null(value[[part]])
    ) {
      return(default)
    }

    value <- value[[part]]
  }

  value
}

normalise_organism <- function(organism) {
  organism <- tolower(
    trimws(as.character(organism))
  )

  if (
    organism %in%
      c(
        "mouse",
        "mus_musculus",
        "mus musculus",
        "mmusculus"
      )
  ) {
    return("mouse")
  }

  if (
    organism %in%
      c(
        "human",
        "homo_sapiens",
        "homo sapiens",
        "hsapiens"
      )
  ) {
    return("human")
  }

  organism
}

safe_percentage_feature_set <- function(
  seu,
  assay,
  pattern,
  column_name
) {
  feature_names <- rownames(
    seu[[assay]]
  )

  matching_features <- grep(
    pattern = pattern,
    x = feature_names,
    value = TRUE
  )

  if (length(matching_features) == 0) {
    message(
      "No features detected for ",
      column_name,
      " using pattern: ",
      pattern
    )

    seu[[column_name]] <- 0
    return(seu)
  }

  message(
    column_name,
    " features detected: ",
    length(matching_features)
  )

  seu[[column_name]] <- PercentageFeatureSet(
    object = seu,
    assay = assay,
    features = matching_features
  )

  seu
}

safe_complexity <- function(
  feature_count,
  molecule_count
) {
  result <- rep(
    NA_real_,
    length(feature_count)
  )

  valid <- (
    !is.na(feature_count) &
    !is.na(molecule_count) &
    feature_count > 0 &
    molecule_count > 1
  )

  result[valid] <- (
    log10(feature_count[valid]) /
      log10(molecule_count[valid])
  )

  result
}

safe_numeric_summary <- function(
  values,
  prefix
) {
  values <- as.numeric(values)
  finite_values <- values[
    is.finite(values)
  ]

  if (length(finite_values) == 0) {
    return(
      tibble(
        metric = c(
          paste0(prefix, "_min"),
          paste0(prefix, "_q25"),
          paste0(prefix, "_median"),
          paste0(prefix, "_mean"),
          paste0(prefix, "_q75"),
          paste0(prefix, "_max")
        ),
        value = NA_real_
      )
    )
  }

  tibble(
    metric = c(
      paste0(prefix, "_min"),
      paste0(prefix, "_q25"),
      paste0(prefix, "_median"),
      paste0(prefix, "_mean"),
      paste0(prefix, "_q75"),
      paste0(prefix, "_max")
    ),
    value = c(
      min(finite_values),
      unname(
        quantile(
          finite_values,
          probs = 0.25
        )
      ),
      median(finite_values),
      mean(finite_values),
      unname(
        quantile(
          finite_values,
          probs = 0.75
        )
      ),
      max(finite_values)
    )
  )
}

first_existing_column <- function(
  metadata,
  candidates
) {
  existing <- candidates[
    candidates %in% colnames(metadata)
  ]

  if (length(existing) == 0) {
    return(NULL)
  }

  existing[[1]]
}

# ============================================================
# Load configuration
# ============================================================

message_step("Loading configuration")

check_file(
  opt$config,
  "configuration file"
)

config <- yaml::read_yaml(
  opt$config
)

organism <- normalise_organism(
  get_config_value(
    config,
    "project.organism",
    "unknown"
  )
)

material <- tolower(
  get_config_value(
    config,
    "project.material",
    get_config_value(
      config,
      "experiment.material",
      "cells"
    )
  )
)

configured_sample_column <- get_config_value(
  config,
  "project.sample_column",
  NULL
)

configured_group_column <- get_config_value(
  config,
  "project.group_column",
  NULL
)

message("Organism: ", organism)
message("Material: ", material)

message(
  "Configured sample column: ",
  if (is.null(configured_sample_column)) {
    "not defined"
  } else {
    configured_sample_column
  }
)

message(
  "Configured group column: ",
  if (is.null(configured_group_column)) {
    "not defined"
  } else {
    configured_group_column
  }
)

# ============================================================
# Load Seurat object
# ============================================================

message_step("Loading Seurat object")

check_file(
  opt$input,
  "input Seurat object"
)

seu <- readRDS(
  opt$input
)

if (!inherits(seu, "Seurat")) {
  stop(
    "Input object is not a Seurat object."
  )
}

cells_before <- ncol(seu)
features_before <- nrow(seu)

message("Input cells: ", cells_before)
message("Input features: ", features_before)
message(
  "Available assays: ",
  paste(
    Assays(seu),
    collapse = ", "
  )
)

if (!"RNA" %in% Assays(seu)) {
  stop(
    paste0(
      "RNA assay not found. Available assays: ",
      paste(
        Assays(seu),
        collapse = ", "
      )
    )
  )
}

DefaultAssay(seu) <- "RNA"

# ============================================================
# Standardise metadata identifiers
# ============================================================

message_step("Standardising metadata")

metadata <- seu@meta.data

sample_candidates <- unique(
  c(
    configured_sample_column,
    "sample",
    "SampleName",
    "ShortName",
    "sample_id",
    "orig.ident"
  )
)

sample_candidates <- sample_candidates[
  !is.na(sample_candidates) &
    nzchar(sample_candidates)
]

sample_source <- first_existing_column(
  metadata,
  sample_candidates
)

if (is.null(sample_source)) {
  warning(
    paste0(
      "No sample metadata column was found. ",
      "All cells will be assigned to 'sample'."
    )
  )

  seu$sample <- "sample"
} else {
  seu$sample <- as.character(
    metadata[[sample_source]]
  )

  message(
    "Sample identifier source: ",
    sample_source
  )
}

group_candidates <- unique(
  c(
    configured_group_column,
    "Group",
    "group",
    "condition"
  )
)

group_candidates <- group_candidates[
  !is.na(group_candidates) &
    nzchar(group_candidates)
]

group_source <- first_existing_column(
  metadata,
  group_candidates
)

if (is.null(group_source)) {
  seu$Group <- NA_character_
  message(
    "No group column found. Group set to NA."
  )
} else {
  seu$Group <- as.character(
    metadata[[group_source]]
  )

  message(
    "Group identifier source: ",
    group_source
  )
}

seu$cell_id <- colnames(seu)

# ============================================================
# RNA QC metrics
# ============================================================

message_step("Calculating RNA QC metrics")

if (organism == "mouse") {
  mitochondrial_pattern <- "^mt-"
  ribosomal_pattern <- "^(Rpl|Rps)"
  globin_pattern <- "^(Hba|Hbb|Hb[ab])"
} else if (organism == "human") {
  mitochondrial_pattern <- "^MT-"
  ribosomal_pattern <- "^(RPL|RPS)"
  globin_pattern <- "^(HBA|HBB|HB[AB])"
} else {
  warning(
    paste0(
      "Unsupported or unknown organism: ",
      organism,
      ". Using case-insensitive patterns."
    )
  )

  mitochondrial_pattern <- "^(MT-|mt-)"
  ribosomal_pattern <- "^(RPL|RPS|Rpl|Rps)"
  globin_pattern <- "^(HBA|HBB|HB[AB]|Hba|Hbb|Hb[ab])"
}

seu <- safe_percentage_feature_set(
  seu = seu,
  assay = "RNA",
  pattern = mitochondrial_pattern,
  column_name = "percent.mito"
)

seu <- safe_percentage_feature_set(
  seu = seu,
  assay = "RNA",
  pattern = ribosomal_pattern,
  column_name = "percent.ribo"
)

seu <- safe_percentage_feature_set(
  seu = seu,
  assay = "RNA",
  pattern = globin_pattern,
  column_name = "percent.globin"
)

required_rna_columns <- c(
  "nCount_RNA",
  "nFeature_RNA"
)

missing_rna_columns <- setdiff(
  required_rna_columns,
  colnames(seu@meta.data)
)

if (length(missing_rna_columns) > 0) {
  stop(
    paste0(
      "Missing RNA metadata columns: ",
      paste(
        missing_rna_columns,
        collapse = ", "
      )
    )
  )
}

seu$log10GenesPerUMI <- safe_complexity(
  feature_count = seu$nFeature_RNA,
  molecule_count = seu$nCount_RNA
)

seu$qc_material <- material
seu$qc_organism <- organism

# ============================================================
# Optional ADT metrics
# ============================================================

message_step("Checking optional modalities")

if ("ADT" %in% Assays(seu)) {
  message(
    "ADT assay detected. Preserving ADT metrics."
  )

  if (
    !"nCount_ADT" %in%
      colnames(seu@meta.data)
  ) {
    warning(
      "ADT assay found but nCount_ADT is missing."
    )
  }

  if (
    !"nFeature_ADT" %in%
      colnames(seu@meta.data)
  ) {
    warning(
      "ADT assay found but nFeature_ADT is missing."
    )
  }
} else {
  message("ADT assay not detected.")
}

if ("HTO" %in% Assays(seu)) {
  message(
    "HTO assay detected. HTO demultiplexing ",
    "will be performed in SAMPLE_RESOLUTION."
  )
} else {
  message("HTO assay not detected.")
}

# ============================================================
# Global summary
# ============================================================

message_step("Creating global QC summary")

qc_summary <- bind_rows(
  tibble(
    metric = c(
      "cells",
      "rna_features",
      "sample_count",
      "group_count",
      "rna_assay_present",
      "adt_assay_present",
      "hto_assay_present"
    ),
    value = c(
      ncol(seu),
      nrow(seu[["RNA"]]),
      n_distinct(seu$sample),
      n_distinct(
        seu$Group[
          !is.na(seu$Group)
        ]
      ),
      1,
      as.integer(
        "ADT" %in% Assays(seu)
      ),
      as.integer(
        "HTO" %in% Assays(seu)
      )
    )
  ),
  safe_numeric_summary(
    seu$nCount_RNA,
    "nCount_RNA"
  ),
  safe_numeric_summary(
    seu$nFeature_RNA,
    "nFeature_RNA"
  ),
  safe_numeric_summary(
    seu$percent.mito,
    "percent_mito"
  ),
  safe_numeric_summary(
    seu$percent.ribo,
    "percent_ribo"
  ),
  safe_numeric_summary(
    seu$percent.globin,
    "percent_globin"
  ),
  safe_numeric_summary(
    seu$log10GenesPerUMI,
    "log10GenesPerUMI"
  )
)

if (
  "nCount_ADT" %in%
    colnames(seu@meta.data)
) {
  qc_summary <- bind_rows(
    qc_summary,
    safe_numeric_summary(
      seu$nCount_ADT,
      "nCount_ADT"
    )
  )
}

if (
  "nFeature_ADT" %in%
    colnames(seu@meta.data)
) {
  qc_summary <- bind_rows(
    qc_summary,
    safe_numeric_summary(
      seu$nFeature_ADT,
      "nFeature_ADT"
    )
  )
}

# ============================================================
# Per-sample summary
# ============================================================

message_step("Creating per-sample QC summary")

qc_by_sample <- seu@meta.data %>%
  as_tibble() %>%
  group_by(
    sample,
    Group
  ) %>%
  summarise(
    cells = n(),
    median_nCount_RNA = median(
      nCount_RNA,
      na.rm = TRUE
    ),
    median_nFeature_RNA = median(
      nFeature_RNA,
      na.rm = TRUE
    ),
    median_percent_mito = median(
      percent.mito,
      na.rm = TRUE
    ),
    median_percent_ribo = median(
      percent.ribo,
      na.rm = TRUE
    ),
    median_percent_globin = median(
      percent.globin,
      na.rm = TRUE
    ),
    median_log10GenesPerUMI = median(
      log10GenesPerUMI,
      na.rm = TRUE
    ),
    .groups = "drop"
  )

if (
  "nCount_ADT" %in%
    colnames(seu@meta.data)
) {
  adt_by_sample <- seu@meta.data %>%
    as_tibble() %>%
    group_by(
      sample,
      Group
    ) %>%
    summarise(
      median_nCount_ADT = median(
        nCount_ADT,
        na.rm = TRUE
      ),
      .groups = "drop"
    )

  qc_by_sample <- left_join(
    qc_by_sample,
    adt_by_sample,
    by = c(
      "sample",
      "Group"
    )
  )
}

if (
  "nFeature_ADT" %in%
    colnames(seu@meta.data)
) {
  adt_features_by_sample <- seu@meta.data %>%
    as_tibble() %>%
    group_by(
      sample,
      Group
    ) %>%
    summarise(
      median_nFeature_ADT = median(
        nFeature_ADT,
        na.rm = TRUE
      ),
      .groups = "drop"
    )

  qc_by_sample <- left_join(
    qc_by_sample,
    adt_features_by_sample,
    by = c(
      "sample",
      "Group"
    )
  )
}

# ============================================================
# Cell-level metadata
# ============================================================

message_step("Preparing cell-level metadata")

qc_metric_columns <- c(
  "cell_id",
  "sample",
  "Group",
  "nCount_RNA",
  "nFeature_RNA",
  "percent.mito",
  "percent.ribo",
  "percent.globin",
  "log10GenesPerUMI",
  "qc_material",
  "qc_organism"
)

optional_metric_columns <- c(
  "nCount_ADT",
  "nFeature_ADT",
  "nCount_HTO",
  "nFeature_HTO"
)

qc_metric_columns <- unique(
  c(
    qc_metric_columns,
    optional_metric_columns[
      optional_metric_columns %in%
        colnames(seu@meta.data)
    ]
  )
)

cell_metadata <- seu@meta.data %>%
  as_tibble(
    rownames = "metadata_row"
  ) %>%
  select(
    any_of(qc_metric_columns)
  )

# ============================================================
# Contract validation
# ============================================================

message_step("Validating QC_METRICS contract")

cells_after <- ncol(seu)
features_after <- nrow(seu)

if (cells_after != cells_before) {
  stop(
    paste0(
      "QC_METRICS changed the number of cells: ",
      cells_before,
      " -> ",
      cells_after
    )
  )
}

if (features_after != features_before) {
  stop(
    paste0(
      "QC_METRICS changed the number of features: ",
      features_before,
      " -> ",
      features_after
    )
  )
}

message(
  "Cell count preserved: ",
  cells_before
)

message(
  "Feature count preserved: ",
  features_before
)

# ============================================================
# Save outputs
# ============================================================

message_step("Saving outputs")

saveRDS(
  seu,
  opt$output,
  compress = TRUE
)

write_csv(
  qc_summary,
  "01a_qc_metrics_summary.csv"
)

write_csv(
  qc_by_sample,
  "01a_qc_metrics_by_sample.csv"
)

write_csv(
  cell_metadata,
  "01a_qc_metrics_cell_metadata.csv"
)

sink(
  "01a_sessionInfo.txt"
)

print(
  sessionInfo()
)

sink()

message(
  "QC metrics object saved in: ",
  opt$output
)

message(
  "Global summary saved in: ",
  "01a_qc_metrics_summary.csv"
)

message(
  "Per-sample summary saved in: ",
  "01a_qc_metrics_by_sample.csv"
)

message(
  "Cell metadata saved in: ",
  "01a_qc_metrics_cell_metadata.csv"
)

message(
  "Session information saved in: ",
  "01a_sessionInfo.txt"
)

message_step(
  "01a_qc_metrics finished successfully"
)
