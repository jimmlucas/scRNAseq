check_file <- function(
  path,
  label = "file"
) {

  if (!file.exists(path)) {

    stop(
      "File does not exist - ",
      label,
      ": ",
      path
    )
  }
}


get_config_value <- function(
  config,
  path,
  default = NULL
) {

  parts <- strsplit(
    path,
    "\\."
  )[[1]]

  value <- config

  for (part in parts) {

    if (
      is.null(value) ||
      is.null(value[[part]])
    ) {
      return(default)
    }

    value <- value[[part]]
  }

  value
}


normalise_organism <- function(organism) {

  organism <- tolower(
    trimws(
      as.character(organism)
    )
  )

  if (
    organism %in%
      c(
        "mouse",
        "mus_musculus",
        "mus musculus",
        "mmusculus"
      )
  ) {
    return("mouse")
  }

  if (
    organism %in%
      c(
        "human",
        "homo_sapiens",
        "homo sapiens",
        "hsapiens"
      )
  ) {
    return("human")
  }

  organism
}


first_existing_column <- function(
  metadata,
  candidates
) {

  candidates <- candidates[
    !is.na(candidates) &
      nzchar(candidates)
  ]

  existing <- candidates[
    candidates %in%
      colnames(metadata)
  ]

  if (length(existing) == 0) {
    return(NULL)
  }

  existing[[1]]
}


safe_complexity <- function(
  feature_count,
  molecule_count
) {

  result <- rep(
    NA_real_,
    length(feature_count)
  )

  valid <- (
    !is.na(feature_count) &
      !is.na(molecule_count) &
      feature_count > 0 &
      molecule_count > 1
  )

  result[valid] <- (
    log10(
      feature_count[valid]
    ) /
      log10(
        molecule_count[valid]
      )
  )

  result
}


safe_numeric_summary <- function(
  values,
  prefix
) {

  values <- suppressWarnings(
    as.numeric(values)
  )

  finite_values <- values[
    is.finite(values)
  ]

  if (length(finite_values) == 0) {

    return(
      tibble(
        metric = c(
          paste0(prefix, "_min"),
          paste0(prefix, "_q25"),
          paste0(prefix, "_median"),
          paste0(prefix, "_mean"),
          paste0(prefix, "_q75"),
          paste0(prefix, "_max")
        ),
        value = NA_real_
      )
    )
  }

  tibble(
    metric = c(
      paste0(prefix, "_min"),
      paste0(prefix, "_q25"),
      paste0(prefix, "_median"),
      paste0(prefix, "_mean"),
      paste0(prefix, "_q75"),
      paste0(prefix, "_max")
    ),
    value = c(
      min(finite_values),
      unname(
        quantile(
          finite_values,
          probs = 0.25
        )
      ),
      median(finite_values),
      mean(finite_values),
      unname(
        quantile(
          finite_values,
          probs = 0.75
        )
      ),
      max(finite_values)
    )
  )
}


get_default_patterns <- function(organism) {

  if (organism == "mouse") {

    return(
      list(
        mitochondrial = "^mt-",
        ribosomal = "^(Rpl|Rps)",
        globin = "^(Hba|Hbb)"
      )
    )
  }

  if (organism == "human") {

    return(
      list(
        mitochondrial = "^MT-",
        ribosomal = "^(RPL|RPS)",
        globin = "^(HBA|HBB)"
      )
    )
  }

  list(
    mitochondrial = "^(MT-|mt-)",
    ribosomal = "^(RPL|RPS|Rpl|Rps)",
    globin = "^(HBA|HBB|Hba|Hbb)"
  )
}


calculate_percentage_metric <- function(
  seu,
  assay,
  pattern,
  column_name
) {

  feature_names <- rownames(
    seu[[assay]]
  )

  matching_features <- grep(
    pattern = pattern,
    x = feature_names,
    value = TRUE
  )

  message(
    column_name,
    " features detected: ",
    length(matching_features),
    " [pattern: ",
    pattern,
    "]"
  )

  if (length(matching_features) == 0) {

    warning(
      "No features detected for ",
      column_name,
      ". Metric set to NA rather than 0."
    )

    seu[[column_name]] <- rep(
      NA_real_,
      ncol(seu)
    )

  } else {

    seu[[column_name]] <- PercentageFeatureSet(
      object = seu,
      assay = assay,
      features = matching_features
    )
  }

  list(
    seu = seu,
    audit = tibble(
      metric = column_name,
      pattern = pattern,
      n_matching_features = length(matching_features)
    )
  )
}


summarise_qc_group <- function(
  metadata,
  grouping_columns
) {

  grouping_columns <- grouping_columns[
    grouping_columns %in%
      colnames(metadata)
  ]

  if (length(grouping_columns) == 0) {
    return(NULL)
  }

  metadata %>%
    as_tibble() %>%
    group_by(
      across(
        all_of(grouping_columns)
      ),
      .drop = FALSE
    ) %>%
    summarise(
      cells = n(),
      median_nCount_RNA = median(
        nCount_RNA,
        na.rm = TRUE
      ),
      median_nFeature_RNA = median(
        nFeature_RNA,
        na.rm = TRUE
      ),
      median_percent_mito = median(
        percent.mito,
        na.rm = TRUE
      ),
      median_percent_ribo = median(
        percent.ribo,
        na.rm = TRUE
      ),
      median_percent_globin = median(
        percent.globin,
        na.rm = TRUE
      ),
      median_log10GenesPerUMI = median(
        log10GenesPerUMI,
        na.rm = TRUE
      ),
      median_nCount_ADT = if (
        "nCount_ADT" %in%
          colnames(metadata)
      ) {
        median(
          nCount_ADT,
          na.rm = TRUE
        )
      } else {
        NA_real_
      },
      median_nFeature_ADT = if (
        "nFeature_ADT" %in%
          colnames(metadata)
      ) {
        median(
          nFeature_ADT,
          na.rm = TRUE
        )
      } else {
        NA_real_
      },
      .groups = "drop"
    )
}


