# ==============================================================================
# 01a_qc_metrics.R
#
# Generic, non-destructive QC metric calculation for scRNAseq.
#
# RESPONSIBILITIES
#   ✓ calculate RNA QC metrics
#   ✓ preserve all cells
#   ✓ preserve all assays (RNA / ADT / HTO / others)
#   ✓ preserve all pre-existing metadata
#   ✓ use configurable sample/group identifiers
#   ✓ preserve Rhapsody/capture provenance when present
#   ✓ write global, per-sample, per-capture and cell-level audit outputs
#
# THIS SCRIPT MUST NOT
#   ✗ filter cells
#   ✗ remove multiplets
#   ✗ remove undetermined cells
#   ✗ remove unmapped cells
#   ✗ normalize
#   ✗ run PCA/UMAP/clustering
#   ✗ decide QC thresholds
#   ✗ decide doublet status
# ==============================================================================


